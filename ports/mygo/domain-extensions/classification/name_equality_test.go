// Source TaskClassification.swift:3487,3581 uses Swift String equality,
// not byte equality and not NFKC_Casefold key equality. The exact-name adapter
// below is deliberately synthetic; it does not implement classification folding.
func TestRenameCanonicalDisplayNoopPreservesFacts(t *testing.T) {
	for _, kind := range []Kind{Category, Label} {
		for _, pair := range [][2]string{{"É", "E\u0301"}, {"각", "\u1100\u1161\u11a8"}, {"A\u0323\u0301", "Á\u0323"}} {
			t.Run(string(kind)+"/"+pair[0], func(t *testing.T) {
				n := FixtureCanonicalizer{"synthetic-display-equality-v1", map[string]CanonicalName{pair[0]: {pair[0], "same-key"}, pair[1]: {pair[1], "same-key"}}}
				e, err := New(n)
				if err != nil {
					t.Fatal(err)
				}
				f := &fixture{t, e, graph(), 100}
				item := Ref{kind, id(20)}
				f.run(Command{Operation: Create, Item: item, Name: pair[0]})
				before := e.Snapshot()
				command := f.command(Command{Operation: Rename, Item: item, Name: pair[1]})
				receipt, err := e.Execute(command, f.g)
				if err != nil {
					t.Fatal(err)
				}
				after := e.Snapshot()
				if receipt.Changed || after.Revision != before.Revision || !reflect.DeepEqual(after.Items, before.Items) {
					t.Fatal("canonically equivalent spelling created a rename or rewrote stored display bytes")
				}
				if len(after.Records) != len(before.Records)+1 {
					t.Fatal("no-op receipt omitted from this Go module's replay record")
				}
				replay, err := RestoreSnapshot(n, after, f.g)
				if err != nil {
					t.Fatal(err)
				}
				if !reflect.DeepEqual(replay.Snapshot(), after) {
					t.Fatal("no-op changed during replay")
				}
				again, err := e.Execute(command, f.g)
				if err != nil || again != receipt || !reflect.DeepEqual(e.Snapshot(), after) {
					t.Fatal("duplicate no-op changed state", err)
				}
			})
		}
	}
}

func TestRenameSameFoldKeyDistinctDisplayMustChange(t *testing.T) {
	plain := strings.Repeat("\u0301", 31)
	withCGJ := strings.Repeat("\u0301", 30) + "\u034f\u0301"
	for _, kind := range []Kind{Category, Label} {
		for _, pair := range [][2]string{{"ABC", "abc"}, {"ＡＢＣ", "ABC"}, {"Straße", "STRASSE"}, {plain, withCGJ}} {
			t.Run(string(kind)+"/"+pair[0], func(t *testing.T) {
				n := FixtureCanonicalizer{"synthetic-display-equality-v1", map[string]CanonicalName{pair[0]: {pair[0], "same-key"}, pair[1]: {pair[1], "same-key"}}}
				e, err := New(n)
				if err != nil {
					t.Fatal(err)
				}
				f := &fixture{t, e, graph(), 100}
				item := Ref{kind, id(20)}
				f.run(Command{Operation: Create, Item: item, Name: pair[0]})
				before := e.Snapshot()
				receipt := f.run(Command{Operation: Rename, Item: item, Name: pair[1]})
				after := e.Snapshot()
				got := after.Items[item.key()]
				if !receipt.Changed || after.Revision != before.Revision+1 || got.Name != pair[1] || len(got.NameVersions) != 2 {
					t.Fatal("fold-key equality or stream-safe NFC swallowed a real display rename")
				}
				if got.NameVersions[0].Name != pair[0] || got.NameVersions[0].ValidUntil == nil {
					t.Fatal("old display history rewritten")
				}
				replay, err := RestoreSnapshot(n, after, f.g)
				if err != nil || !reflect.DeepEqual(replay.Snapshot(), after) {
					t.Fatal("distinct rename replay", err)
				}
			})
		}
	}
}

// This exact synthetic file was generated by the old engine at a91eba40.
// Preserve it as evidence; do not silently rewrite historical records to fit the fix.
func TestRenameLegacyEquivalentRecordRejectedWithoutRewrite(t *testing.T) {
	data, err := os.ReadFile("testdata/legacy-equivalent-rename.json")
	if err != nil {
		t.Fatal(err)
	}
	var old Snapshot
	if err = json.Unmarshal(data, &old); err != nil {
		t.Fatal(err)
	}
	before, err := json.Marshal(old)
	if err != nil {
		t.Fatal(err)
	}
	n := FixtureCanonicalizer{"unicode-fixture-nfkc-casefold-whitespace-v1", map[string]CanonicalName{"É": {"É", "é"}, "E\u0301": {"E\u0301", "é"}}}
	if _, err = RestoreSnapshot(n, old, graph()); !errors.Is(err, ErrInvalid) {
		t.Fatal("old erroneous advancing record silently accepted", err)
	}
	after, err := json.Marshal(old)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(before, after) {
		t.Fatal("rejected legacy record rewritten")
	}
	disk, err := os.ReadFile("testdata/legacy-equivalent-rename.json")
	if err != nil || !bytes.Equal(data, disk) {
		t.Fatal("legacy fixture changed", err)
	}
}
