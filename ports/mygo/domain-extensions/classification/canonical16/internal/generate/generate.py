"""只解析已校验的 Unicode16 文本；不使用 Python/Go 的 Unicode 属性表。"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE_MANIFEST_SHA256 = 'b4e2c156009050d413808ae1dee3c6ffa324ef65e4aeb78961d54a8ce68836c9'
GCB = {'Other': 0, 'CR': 1, 'LF': 2, 'Control': 3, 'Extend': 4, 'ZWJ': 5,
       'Regional_Indicator': 6, 'Prepend': 7, 'SpacingMark': 8, 'L': 9,
       'V': 10, 'T': 11, 'LV': 12, 'LVT': 13}
INCB = {'None': 0, 'Consonant': 1, 'Extend': 2, 'Linker': 3}

def sha(data):
    return hashlib.sha256(data).hexdigest()

def records(path):
    for line in path.read_text(encoding='utf-8').splitlines():
        body = line.split('#', 1)[0].strip()
        if body:
            yield [part.strip() for part in body.split(';')]

def span(value):
    parts = value.split('..')
    return range(int(parts[0], 16), int(parts[-1], 16) + 1)

def literal(cps):
    return '"' + ''.join(('\\u%04x' if cp <= 0xffff else '\\U%08x') % cp for cp in cps) + '"'

def generate(ucd):
    manifest_data = (ucd / 'SOURCE.json').read_bytes()
    if sha(manifest_data) != SOURCE_MANIFEST_SHA256:
        raise ValueError('SOURCE.json differs from the pinned manifest')
    manifest = json.loads(manifest_data)
    if manifest['unicode_version'] != '16.0.0':
        raise ValueError('not Unicode16')
    for entry in manifest['files'] + [manifest['license']]:
        data = (ucd / entry['path']).read_bytes()
        if sha(data) != entry['sha256']:
            raise ValueError('source checksum mismatch: ' + entry['path'])
        if 'bytes' in entry and len(data) != entry['bytes']:
            raise ValueError('source size mismatch: ' + entry['path'])

    # Packed ranges combine only fixed-version properties used at runtime.
    # Bits: CCC[0:8], GCB[8:12], InCB[12:14], EP[14], White_Space[15].
    props = [0] * 0x110000
    decomposition = {}
    pending = None
    for p in records(ucd / 'UnicodeData.txt'):
        cp, ccc = int(p[0], 16), int(p[3])
        if p[1].endswith(', First>'):
            pending = (cp, ccc)
        elif p[1].endswith(', Last>'):
            if pending is None or pending[1] != ccc:
                raise ValueError('invalid UnicodeData range')
            for value in range(pending[0], cp + 1):
                props[value] |= ccc
            pending = None
        else:
            props[cp] |= ccc
        if p[5] and not p[5].startswith('<'):
            decomposition[cp] = tuple(int(s, 16) for s in p[5].split())
    if pending is not None:
        raise ValueError('unclosed UnicodeData range')

    fold, exclusion = {}, set()
    for p in records(ucd / 'DerivedNormalizationProps.txt'):
        if p[1] == 'NFKC_CF':
            mapping = tuple(int(s, 16) for s in p[2].split())
            for cp in span(p[0]):
                if cp in fold:
                    raise ValueError('duplicate NFKC_CF')
                fold[cp] = mapping
        elif p[1] == 'Full_Composition_Exclusion':
            exclusion.update(span(p[0]))
    for p in records(ucd / 'auxiliary/GraphemeBreakProperty.txt'):
        for cp in span(p[0]):
            props[cp] |= GCB[p[1]] << 8
    for p in records(ucd / 'DerivedCoreProperties.txt'):
        if p[1] == 'InCB':
            if len(p) != 3 or p[2] not in INCB:
                raise ValueError('invalid three-column InCB')
            for cp in span(p[0]):
                props[cp] |= INCB[p[2]] << 12
    for filename, prop, bit in [('emoji/emoji-data.txt', 'Extended_Pictographic', 14),
                               ('PropList.txt', 'White_Space', 15)]:
        for p in records(ucd / filename):
            if p[1] == prop:
                for cp in span(p[0]):
                    props[cp] |= 1 << bit

    composition = []
    for cp, decomp in sorted(decomposition.items()):
        if cp not in exclusion and len(decomp) == 2:
            if props[decomp[0]] & 255:
                raise ValueError('composition starts with nonstarter')
            composition.append(((decomp[0] << 21) | decomp[1], cp))
    if len({pair for pair, _ in composition}) != len(composition):
        raise ValueError('duplicate composition pair')

    out = ['// Code generated by internal/generate/generate.py; DO NOT EDIT.',
           '// Unicode data: Unicode License V3, see testdata/ucd/LICENSE.',
           '// Source manifest SHA-256: ' + SOURCE_MANIFEST_SHA256,
           '// Generator SHA-256: ' + sha(Path(__file__).read_bytes()),
           'package canonical16', '', 'var propertyRanges = [...]propertyRange{']
    lo = 0
    for cp in range(1, len(props) + 1):
        if cp == len(props) or props[cp] != props[lo]:
            if props[lo]:
                out.append('\t{0x%x, 0x%x, 0x%x},' % (lo, cp - 1, props[lo]))
            lo = cp
    out.extend(['}', '', 'var canonicalDecompositions = [...]scalarMapping{'])
    out.extend('\t{0x%x, %s},' % (cp, literal(value)) for cp, value in sorted(decomposition.items()))
    out.extend(['}', '', 'var casefoldMappings = [...]scalarMapping{'])
    out.extend('\t{0x%x, %s},' % (cp, literal(value)) for cp, value in sorted(fold.items()))
    out.extend(['}', '', 'var compositionPairs = [...]compositionPair{'])
    out.extend('\t{0x%x, 0x%x},' % item for item in sorted(composition))
    out.extend(['}', ''])
    return '\n'.join(out).encode()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ucd', type=Path, default=ROOT / 'testdata/ucd')
    parser.add_argument('--output', type=Path, default=ROOT / 'tables_generated.go')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate(args.ucd)
    if args.check:
        if args.output.read_bytes() != output:
            raise SystemExit('generated Unicode16 tables differ')
    else:
        args.output.write_bytes(output)
    print('Unicode16 generated tables SHA-256: ' + sha(output))

if __name__ == '__main__':
    main()
